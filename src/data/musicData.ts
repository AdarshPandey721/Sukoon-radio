export const deduplicateTracks = (tracks: Track[]): Track[] => {
  const seenVideoIds = new Set<string>();
  const seenTitles = new Set<string>();
  const result: Track[] = [];

  for (const track of tracks) {
    const normVideoId = (track.videoId || "").trim();
    const normTitle = (track.title || "").toLowerCase().replace(/[^a-z0-9]/g, "");

    if (normVideoId && seenVideoIds.has(normVideoId)) {
      continue;
    }
    if (normTitle && seenTitles.has(normTitle)) {
      continue;
    }

    if (normVideoId) seenVideoIds.add(normVideoId);
    if (normTitle) seenTitles.add(normTitle);
    result.push(track);
  }

  return result;
};

